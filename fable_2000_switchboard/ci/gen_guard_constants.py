#!/usr/bin/env python3
"""Generate shared guard constants and verify exact names against live PostgreSQL."""
from __future__ import annotations
import argparse, hashlib, json, os, re, sys, unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
import switchboard_engine as E
CORPUS=ROOT/'ci/guard_corpus.jsonl'
DEFAULT_OUT=ROOT/'sql/010_guard_constants.sql'

def lit(value):
    return "E'"+value.replace('\\','\\\\').replace("'","''")+"'"

def py_to_pg(pattern, flags):
    if '(?' in pattern or re.search(r'\\[AZ]',pattern):
        raise ValueError('Unsupported shared regex construct: '+pattern)
    pattern=re.sub(r'\\u([a-fA-F0-9]{4})',lambda m: chr(int(m[1],16)),pattern)
    pattern=pattern.replace(r'\b',r'\y')
    if flags=='full':
        return r'\A'+pattern[1:-1]+r'\Z'
    return ('(?'+('w' if 'm' in flags else '')+('i' if 'i' in flags else '')+')' if flags else '')+pattern

def rows():
    return list(E.shared_guard_patterns())

def source_sha():
    return hashlib.sha256(Path(E.__file__).read_bytes()).hexdigest()

def render():
    lines=['-- GENERATED by ci/gen_guard_constants.py; source: switchboard_engine.py','BEGIN;',
        "SELECT pg_advisory_xact_lock(1943,12090);",
        'CREATE TABLE IF NOT EXISTS public.guard_pattern(kind text NOT NULL,name text PRIMARY KEY,py_regex text NOT NULL,pg_regex text NOT NULL,source_sha text NOT NULL,flags text NOT NULL);',
        "DELETE FROM public.guard_pattern WHERE source_sha <> 'r47';",
        'CREATE TABLE IF NOT EXISTS public.r31b_deployment_object(name text PRIMARY KEY,priority int NOT NULL,ddl text NOT NULL);',
        'REVOKE ALL ON public.r31b_deployment_object FROM PUBLIC,sales_role,pm_sales_finance_role;',
        'CREATE TABLE IF NOT EXISTS public.guard_setting(name text PRIMARY KEY,value_numeric numeric NOT NULL,source_sha text NOT NULL);',
        'INSERT INTO public.guard_setting VALUES('+lit('bank_fee_tolerance_twd')+','+str(E.BANK_FEE_TOLERANCE_TWD)+','+lit(source_sha())+') ON CONFLICT(name) DO UPDATE SET value_numeric=EXCLUDED.value_numeric,source_sha=EXCLUDED.source_sha;',
        'ALTER TABLE public.invoice_fee_adjustment DROP CONSTRAINT IF EXISTS invoice_fee_adjustment_amount_check;',
        'ALTER TABLE public.invoice_fee_adjustment ADD CONSTRAINT invoice_fee_adjustment_amount_check CHECK(amount>0 AND amount<='+str(E.BANK_FEE_TOLERANCE_TWD)+');',
        'UPDATE public.client_playbook_rule SET structured=jsonb_set(structured,ARRAY[\'fee_tolerance_twd\'],to_jsonb('+str(E.BANK_FEE_TOLERANCE_TWD)+'::int)) WHERE rule_code=\'BANK_NOTICE_NEVER_AUTO_UNLOCK\';']
    for kind,name,pattern,flags in rows():
        values=(kind,name,pattern,py_to_pg(pattern,flags),source_sha(),flags)
        lines.append('INSERT INTO public.guard_pattern VALUES('+','.join(map(lit,values))+');')
    lines.extend([r"""
CREATE OR REPLACE FUNCTION public.guard_normalize(p_text text) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
 SELECT replace(replace(translate(normalize(coalesce(p_text,''),NFKC),__FORMAT_CHARS__,''),E'\r\n',E'\n'),E'\r',E'\n') $$;
CREATE OR REPLACE FUNCTION public.guard_hit(p_kind text,p_text text) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT name FROM public.guard_pattern WHERE kind=p_kind
 AND (CASE WHEN p_kind='case_code' THEN p_text ELSE translate(public.guard_normalize(p_text), U&'\200B\200C\200D\2060\FEFF','') END) ~ pg_regex ORDER BY name LIMIT 1 $$;
ALTER TABLE public.outbound_message ADD COLUMN IF NOT EXISTS subject text;
ALTER TABLE public."case" DROP CONSTRAINT IF EXISTS case_code_format_chk;
""",
        'ALTER TABLE public."case" ADD CONSTRAINT case_code_format_chk CHECK ((case_code IS NULL AND status IN (\'preliminary\',\'pending_bucket\')) OR (case_code IS NOT NULL AND case_code <> \'C000000\' AND case_code ~ '+lit(E.CASE_CODE_PATTERN)+')) NOT VALID;',
        (ROOT/'ci/guard_functions.sql').read_text()])
    for rule in E.OTP_WHITELIST:
        lines.append('UPDATE public.otp_forward_rule SET subject_regex='+lit(py_to_pg(rule['subject_re'],'i'))+',code_regex='+lit(py_to_pg(rule['code_re'],''))+' WHERE lower(sender_exact)='+lit(rule['sender'].lower())+';')
    lines.append("""
INSERT INTO public.r31b_deployment_object(name,priority,ddl)
 SELECT p.oid::regprocedure::text,10,pg_get_functiondef(p.oid) FROM pg_proc p
 WHERE p.pronamespace='public'::regnamespace AND p.proname IN ('outbound_guard','switchboard_outbound_guard','otp_deliver','guard_hit','guard_normalize')
 ON CONFLICT(name) DO UPDATE SET ddl=EXCLUDED.ddl,priority=EXCLUDED.priority;
""")
    lines.append('COMMIT;\n')
    return '\n'.join(lines).replace('__FORMAT_CHARS__','||'.join('chr('+str(i)+')' for i in range(sys.maxunicode+1) if unicodedata.category(chr(i))=='Cf'))

def corpus():
    return [json.loads(line) for line in CORPUS.read_text().splitlines() if line.strip()]

def validate_python():
    cases=corpus()
    for case in cases:
        hit=E.guard_hit(case['kind'],case['text'])
        if (hit is not None)!=case['expect']:
            raise AssertionError(f'Python corpus mismatch: {case!r}, hit={hit!r}')
    return len(cases)

def check(dsn, out=DEFAULT_OUT):
    if Path(out).read_text()!=render():
        raise AssertionError('generated SQL is stale')
    count=validate_python()
    import psycopg
    with psycopg.connect(dsn) as conn:
        current_db=conn.execute('SELECT current_database()').fetchone()[0]
        assert current_db != 'yongxiang_plumb', f'FATAL: Test script forbidden from connecting to production DB yongxiang_plumb (got {current_db})'
        actual=conn.execute("SELECT kind,name,py_regex,pg_regex,source_sha,flags FROM public.guard_pattern WHERE source_sha <> 'r47' ORDER BY name").fetchall()
        expected=sorted([(k,n,p,py_to_pg(p,f),source_sha(),f) for k,n,p,f in rows()],key=lambda r:r[1])
        assert actual==expected,'deployed constants differ from source'
        for case in corpus():
            py=E.guard_hit(case['kind'],case['text'])
            pg=conn.execute('SELECT public.guard_hit(%s,%s)',(case['kind'],case['text'])).fetchone()[0]
            assert py==pg, f'first-hit mismatch {case!r}: py={py!r}, pg={pg!r}'
        assert conn.execute("SELECT value_numeric FROM public.guard_setting WHERE name='bank_fee_tolerance_twd'").fetchone()[0]==E.BANK_FEE_TOLERANCE_TWD
        outbound=conn.execute("SELECT pg_get_functiondef('public.outbound_guard()'::regprocedure)").fetchone()[0]
        assert "guard_hit('internal'" in outbound and "guard_hit('forbidden'" in outbound,'deployed outbound trigger was overwritten or is stale'
        constraint=conn.execute("SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid='public.case'::regclass AND conname='case_code_format_chk'").fetchone()[0]
        assert E.CASE_CODE_PATTERN in constraint
    return {'passed':True,'cases':count,'matched':count,'parity_percent':100,'patterns':len(expected),'source_sha256':source_sha()}

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--out',type=Path,default=DEFAULT_OUT); ap.add_argument('--check',action='store_true');ap.add_argument('--dsn',default=os.environ.get('PG_DSN','dbname=yongxiang_plumb_r39_clone'))
    a=ap.parse_args()
    if a.check:
        if not a.dsn: ap.error('--check requires --dsn or PG_DSN (PostgreSQL verification cannot be called PASS without a DB)')
        print(json.dumps(check(a.dsn,a.out),ensure_ascii=False))
    else:
        a.out.parent.mkdir(parents=True,exist_ok=True); a.out.write_text(render());print(a.out)
if __name__=='__main__': main()
