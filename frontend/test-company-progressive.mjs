import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import React,{act} from 'react';
import {createRoot} from 'react-dom/client';
import {a,workspace} from './session-epoch-fixture.mjs';

const bundle=await build({entryPoints:['src/App.tsx'],bundle:true,write:false,platform:'node',format:'esm',jsx:'automatic',packages:'external',loader:{'.css':'empty'}});
const bundlePath=new URL('./.company-progressive-bundle.mjs',import.meta.url);
await fs.writeFile(bundlePath,bundle.outputFiles[0].text);
let App;try{App=(await import(bundlePath.href)).default}finally{await fs.unlink(bundlePath)}
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost/#view=company',pretendToBeVisual:true});
for(const key of ['window','document','location','history','sessionStorage','FormData','Event','HTMLElement'])globalThis[key]=dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.requestAnimationFrame=dom.window.requestAnimationFrame.bind(dom.window);
dom.window.scrollTo=()=>{};
const requests=[];let resolveWorkspace;let resolveCockpit;let currentUser=a;
const payload={as_of:'2026-10-14',checked_at:'2026-10-14T12:00:00Z',source:{status:'partial',mapping_status:'unknown',last_success_at:'2026-10-01T00:00:00Z'},totals:{cases:0,confirmed_cases:0,intake_records:0,workbench_cases:0,deliveries_confirmed:0,tasks_total:0,tasks_completed:0,tasks_overdue:0,pending_local_reviews:0,pending_native_reviews:0,lifecycle_counts:{}},missing:{task_due_date:0,group:0,source_status:0},groups:[],cases:[],pagination:{offset:0,limit:40,total:0,has_more:false}};
globalThis.fetch=async(url)=>{
 requests.push(String(url));
 if(url==='/api/session')return new Response(JSON.stringify({user:currentUser,users:[currentUser],mode:'lark',environment:'production',workspace_id:'workspace-A',auth_configured:true}));
 if(url==='/api/workspace')return new Promise(resolve=>{resolveWorkspace=resolve});
 if(String(url).startsWith('/api/company-dashboard'))return new Promise(resolve=>{resolveCockpit=resolve});
 throw Error('Unexpected endpoint '+url);
};
const root=createRoot(document.getElementById('root'));
const flush=async(fn=()=>{})=>act(async()=>{await fn();await new Promise(r=>setTimeout(r,0))});
await flush(()=>root.render(React.createElement(App)));
await flush();
assert.ok(resolveWorkspace,'workspace load remains in flight');
assert.equal(requests.filter(url=>url.startsWith('/api/company-dashboard')).length,1,'cockpit starts its own request before the workspace is ready');
assert.match(document.querySelector('.company-cockpit').textContent,/公司駕駛艙/);
assert.match(document.querySelector('.cockpit-loading').textContent,/正在讀取/);
await flush(()=>resolveCockpit(new Response(JSON.stringify(payload))));
assert.ok(document.querySelector('.cockpit-freshness'),'cockpit renders its available snapshot while the workspace is still pending');
assert.match(document.querySelector('.cockpit-freshness').textContent,/待核對/,'partial source never becomes complete');
assert.match(document.querySelector('.cockpit-freshness').textContent,/2026\/10\/01/,'old source time stays old');
await flush(()=>resolveWorkspace(new Response(JSON.stringify(workspace))));
assert.equal(requests.filter(url=>url.startsWith('/api/company-dashboard')).length,1,'first workspace response does not duplicate the cockpit request');
currentUser={...a,id:'different-session-user'};
await flush(()=>document.querySelector('[aria-label="重新整理資料"]').click());
await flush();
assert.ok(document.querySelector('.cockpit-loading'),'identity change remounts the cockpit with its own skeleton');
assert.equal(document.querySelector('.cockpit-freshness'),null,'previous identity snapshot is hidden immediately');
assert.equal(requests.filter(url=>url.startsWith('/api/company-dashboard')).length,2,'new identity makes its own authenticated request');
await flush(()=>resolveCockpit(new Response(JSON.stringify(payload))));
assert.ok(document.querySelector('.cockpit-freshness'),'new identity renders only its response');
await flush(()=>root.unmount());
dom.window.close();
console.log('Company progressive load: 12 checks passed');
