import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=await build({entryPoints:[new URL('./src/api.ts',import.meta.url).pathname],bundle:true,write:false,format:'esm',platform:'node',packages:'external'});
const js=bundle.outputFiles[0].text;
const {readRoute,normalizeRoute}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
globalThis.location={hash:'#view=company'};
assert.equal(readRoute().view,'projects','company deep link falls back to projects');
assert.equal(normalizeRoute({view:'company'}).view,'projects');
assert.equal(normalizeRoute({view:'schedule'}).view,'projects','removed schedule links fall back to projects');
globalThis.location={hash:''};
assert.equal(readRoute().view,'dashboard','personal default home remains');
globalThis.location={hash:'#view=project&project=case%2F123'};
assert.equal(readRoute().project,'case/123','case links preserve identifiers');
console.log('Removed routes: 5 checks passed');
