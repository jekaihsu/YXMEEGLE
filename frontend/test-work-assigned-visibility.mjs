const bundle=await build({stdin:{contents:"export {isHomeAssigned,isHomeProxy} from './src/executableTasks';",resolveDir:process.cwd(),loader:'tsx'},bundle:true,write:false,platform:'node',format:'esm',packages:'external'});
const url='data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64');
