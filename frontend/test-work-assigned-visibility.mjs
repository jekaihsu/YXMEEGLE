assert.ok(/待前置成果交付/.test(app)&&/任務暫停，原因待核對/.test(app),'My Work explains prerequisite and paused assigned work');
assert.ok(/排程尚未開始/.test(app),'My Work explains upcoming assigned work');
assert.ok(/目前尚未開放執行/.test(app),'My Work explains other assigned waiting work');
assert.ok(/waiting\.map\(\(\{r,reason\}\)/.test(app)&&/openTask\(c,r\)/.test(app),'waiting rows display individual reasons and still navigate to the task');
