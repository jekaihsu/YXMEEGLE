const work={...w,version:1,environment:'demo',projects:[project],users:[{id:'viewer',name:'Viewer',role:'member'},{id:'coworker',name:'Colleague',role:'member'}],approvals:[],events:[],calendar:{holidays:[],workdays:[]},source_status:{status:'ready'},workspace_id:'test'};
