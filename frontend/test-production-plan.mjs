import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {writeFile,unlink} from 'node:fs/promises';
const bundle=await build({entryPoints:['src/productionPlan.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const file=new URL('./.production-plan-test.mjs',import.meta.url);
await writeFile(file,bundle.outputFiles[0].text);
const {isProductionSeedTask,productionPlanFacts}=await import(file.href);await unlink(file);
const task={title:'外業：依計畫數量完成',detail:'依計畫數量完成外業。\n計畫數量：65\n合約明細：3 筆；工項：3 項\n工項連結：原生 1、推導 1、待確認 1、未連結 0\n注意：請核對。\n[SOP-START:v1:field]'};
assert.equal(isProductionSeedTask({title:'核對成果',detail:'核對紀錄'},'field'),false);
assert.equal(productionPlanFacts({title:'核對成果',detail:'計畫數量：65'},'field'),null);
assert.equal(isProductionSeedTask({...task,title:'調整後的任務名稱'},'field'),true);
assert.equal(isProductionSeedTask({...task,detail:''},'field'),true);
assert.equal(isProductionSeedTask(task,'control'),false);
assert.equal(isProductionSeedTask(task,'sales'),false);
for(const [key,label] of [['control','控制'],['mapping','圖資'],['report','報告']])assert.equal(isProductionSeedTask({title:`${label}：依計畫數量完成`,detail:''},key),true);
assert.equal(isProductionSeedTask({title:'一般任務',detail:'文字中提到 [SOP-START:v1:field] 不算標記行'},'field'),false);
const basis=[{key:'native',count:1},{key:'derived',count:1},{key:'ambiguous',count:1},{key:'unlinked',count:0}];
assert.deepEqual(productionPlanFacts(task,'field'),{source:'task-detail',quantity:'65',lines:3,items:3,basis});
const stage={planned:{qty:'72.5',lines:4,items:5,basis:{native:2,derived:2,ambiguous:1,unlinked:0}}};
assert.deepEqual(productionPlanFacts(task,'field',stage),{source:'evidence',quantity:'72.5',lines:4,items:5,basis:[{key:'native',count:2},{key:'derived',count:2},{key:'ambiguous',count:1},{key:'unlinked',count:0}]});
assert.deepEqual(productionPlanFacts(task,'field',{planned:null}),{source:'evidence',quantity:null,lines:null,items:null,basis:[]});
assert.deepEqual(productionPlanFacts({...task,detail:'[SOP-START:v1:field]'},'field'),{source:'task-detail',quantity:null,lines:null,items:null,basis:[]});
assert.doesNotMatch(JSON.stringify(productionPlanFacts(task,'field')),/SOP-START|注意/);
assert.equal(productionPlanFacts({...task,detail:'計畫數量：0\n合約明細：0 筆；工項：0 項'},'field').quantity,'0');
console.log('production seed recognition and evidence facts passed');
