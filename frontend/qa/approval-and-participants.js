async (page) => {
  const results = [];
  await page.getByRole('button', { name: /期限展延 · C115236 QA 控制成果期限調整/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: '送出審批', exact: true }).click();
  await page.getByRole('button', { name: '確認操作', exact: true }).click();
  await page.getByText('等待審批', { exact: true }).last().waitFor();
  let workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  let task = workspace.projects.find(p => p.id === 'p1').nodes.find(n => n.key === 'control').tasks.find(t => t.id === 'p1-control-t3');
  if (task.due_date !== '2026-09-24' || task.status !== 'pending') throw new Error('Extension prematurely changed date or froze task');
  results.push('Extension pending keeps original date and running eligibility');
  await page.getByRole('dialog').getByRole('button', { name: '關閉', exact: true }).first().click();
  await page.locator('.user-button').click();
  await page.getByRole('button', { name: '智偉 張智偉 管理部 · 主管', exact: true }).click();
  await page.locator('.user-button').getByText('張智偉', { exact: true }).waitFor();
  await page.getByRole('button', { name: /期限展延 · C115236 QA 控制成果期限調整/ }).click();
  await page.getByRole('button', { name: '模擬 Lark 通過', exact: true }).click();
  await page.getByRole('button', { name: '套用新期限', exact: true }).waitFor();
  workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  task = workspace.projects.find(p => p.id === 'p1').nodes.find(n => n.key === 'control').tasks.find(t => t.id === 'p1-control-t3');
  if (task.due_date !== '2026-09-24') throw new Error('Approval applied before explicit execute');
  results.push('Approved extension waits for explicit execute');
  await page.getByRole('button', { name: '套用新期限', exact: true }).click();
  await page.getByRole('button', { name: '確認操作', exact: true }).click();
  await page.getByText('已套用', { exact: true }).last().waitFor();
  workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  task = workspace.projects.find(p => p.id === 'p1').nodes.find(n => n.key === 'control').tasks.find(t => t.id === 'p1-control-t3');
  if (task.due_date !== '2026-10-01' || task.original_due_date !== '2026-09-24') throw new Error('Extension lost original date');
  results.push('Execute updates date, preserves original date');
  await page.screenshot({ path: 'output/playwright/meegle-extension-approved.png', fullPage: true });
  await page.getByRole('dialog').getByRole('button', { name: '關閉', exact: true }).first().click();
  await page.locator('.project-tools').getByRole('button', { name: '參與人員', exact: true }).click();
  const control = page.locator('.participant-edit-row').filter({ has: page.getByText('控制', { exact: true }) });
  await control.getByRole('combobox').selectOption('u-agent');
  await page.getByRole('button', { name: '儲存參與人員', exact: true }).click();
  await page.getByRole('dialog', { name: '統一設定參與人員' }).waitFor({ state: 'hidden' });
  workspace = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  const node = workspace.projects.find(p => p.id === 'p1').nodes.find(n => n.key === 'control');
  if (node.owner_id !== 'u-agent' || node.tasks.find(t => t.id === 'p1-control-t3').owner_id !== 'u-agent') throw new Error('Assignment inheritance failed');
  if (node.tasks.find(t => t.id === 'p1-control-t2').owner_id !== 'u-control') throw new Error('Completed history owner changed');
  results.push('Participant update inherits active tasks and preserves completed task owner');
  const comments = node.tasks.find(t => t.id === 'p1-control-t2').comments;
  if (!comments.some(c => c.body === 'QA：已確認成果與交接內容。')) throw new Error('Task comment not persisted');
  results.push('Task output and comment persisted');
  await page.reload();
  await page.getByRole('heading', { name: '桃園捷運綠線控制點測量', exact: true }).waitFor();
  results.push('Deep-link reload preserved project and approvals tab');
  console.log(JSON.stringify(results));
}
