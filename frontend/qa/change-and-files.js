async (page) => {
  const results = [];
  await page.getByRole('button', { name: '設計變更', exact: true }).click();
  await page.getByRole('textbox', { name: '申請標題', exact: true }).fill('QA 控制工項新版');
  await page.getByRole('textbox', { name: '申請原因', exact: true }).fill('QA：追加控制工項，僅暫停同工項下游。');
  await page.getByRole('checkbox', { name: /^控制點平差計算/ }).check();
  await page.getByRole('button', { name: '建立申請草稿', exact: true }).click();
  await page.getByRole('button', { name: /設計變更 · C115236 QA 控制工項新版/ }).click();
  await page.getByRole('button', { name: '送出審批', exact: true }).click();
  await page.getByRole('button', { name: '確認操作', exact: true }).click();
  await page.getByRole('button', { name: '主管確認', exact: true }).waitFor();
  let ws = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  let p = ws.projects.find(p => p.id === 'p1');
  if (p.nodes.find(n => n.key === 'control').tasks.find(t => t.id === 'p1-control-t1').status !== 'paused') throw new Error('Selected work not paused');
  if (p.nodes.find(n => n.key === 'mapping').tasks.find(t => t.id === 'p1-mapping-t1').status !== 'paused') throw new Error('Same work downstream not paused');
  if (p.nodes.find(n => n.key === 'mapping').tasks.find(t => t.id === 'p1-mapping-t2').status !== 'pending') throw new Error('Unrelated work paused');
  results.push('Change freezes affected work and matching downstream only');
  await page.getByRole('button', { name: '主管確認', exact: true }).click();
  await page.getByRole('button', { name: '業主確認', exact: true }).click();
  if (await page.getByRole('button', { name: '手動切換新版', exact: true }).count()) throw new Error('Change approved without Lark');
  await page.getByRole('button', { name: '模擬 Lark 通過', exact: true }).click();
  await page.getByRole('button', { name: '手動切換新版', exact: true }).click();
  await page.getByRole('button', { name: '確認操作', exact: true }).click();
  await page.getByText('已套用', { exact: true }).last().waitFor();
  ws = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  p = ws.projects.find(p => p.id === 'p1');
  const control = p.nodes.find(n => n.key === 'control');
  if (control.tasks.find(t => t.id === 'p1-control-t1').status !== 'superseded') throw new Error('Old version not preserved');
  if (!control.tasks.some(t => t.replaces_task_id === 'p1-control-t1' && t.status === 'pending')) throw new Error('Replacement task missing');
  results.push('Three approvals plus explicit execute creates new tasks and preserves old');
  await page.screenshot({ path: 'output/playwright/meegle-change-approved.png' });
  await page.getByRole('dialog').getByRole('button', { name: '關閉', exact: true }).first().click();
  await page.getByRole('button', { name: /^Input \/ Output/ }).click();
  await page.getByRole('button', { name: '加入連結', exact: true }).click();
  await page.getByRole('textbox', { name: '檔案名稱', exact: true }).fill('QA 工程確認单連結');
  await page.getByRole('textbox', { name: '來源網址', exact: true }).fill('https://yong-xiang-survey.jp.larksuite.com/base/JoOqbggsVar0ATsVgbcjh6IIp1g');
  await page.getByRole('button', { name: '儲存連結', exact: true }).click();
  await page.getByRole('dialog', { name: '加入來源連結' }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '上傳檔案', exact: true }).click();
  await page.getByLabel('選擇檔案', { exact: true }).setInputFiles('C:/Users/asus/Desktop/B4/meegle/frontend/qa/fixture.txt');
  await page.getByRole('dialog', { name: '上傳作業檔案' }).getByRole('button', { name: '上傳檔案', exact: true }).click();
  await page.getByRole('dialog', { name: '上傳作業檔案' }).waitFor({ state: 'hidden' });
  ws = await page.evaluate(async () => (await fetch('/api/workspace')).json());
  p = ws.projects.find(p => p.id === 'p1');
  const uploaded = p.files.find(f => f.name === 'fixture.txt');
  if (!uploaded || !p.files.some(f => f.storage === 'link')) throw new Error('Files not persisted');
  const response = await page.request.get(`http://127.0.0.1:8000/api/files/${uploaded.id}/download`);
  if (response.status() !== 200 || !(await response.text()).includes('Prototype QA fixture')) throw new Error('Authenticated download failed');
  results.push('File link/upload/authenticated download persisted');
  await page.getByRole('button', { name: '流程與任務', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/meegle-project-desktop.png', fullPage: true });
  console.log(JSON.stringify(results));
}
