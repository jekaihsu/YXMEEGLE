assert.doesNotMatch(document.body.textContent,/mock_ui|internal_secret|read_own_work/);
await flush(()=>root.render(React.createElement(SettingsOverview,{s:{mode:'lark',user:{id:'manager',role:'manager'}},workspaceId:'production'})));
await flush(()=>requests.findLast(r=>r.url==='/api/settings/overview').resolve(new Response(JSON.stringify({user:{name:'主管'},directory:{status:'ready',last_success_at:'2026-10-14T15:00:00Z',roster_size:82,matched_accounts:67,linked_identities:0,review_items:15},admin_summary:{templates:[{version:1,status:'published'},{version:2,status:'draft'}],jobs:{loaded:6,blocked:6},attendance:{ready:236,manual:0}}}))));
