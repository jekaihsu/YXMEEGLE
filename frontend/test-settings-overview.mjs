import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import React,{act} from 'react';
import {createRoot} from 'react-dom/client';
const bundle=await build({stdin:{contents:"export {SettingsOverview} from './src/SettingsOverview';",resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm',packages:'external',loader:{'.css':'empty'}});
const path=new URL('./.settings-test-bundle.mjs',import.meta.url);
await fs.writeFile(path,bundle.outputFiles[0].text);
let SettingsOverview;
try{({SettingsOverview}=await import(path.href))}finally{await fs.unlink(path)}
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
for(const name of ['window','document','Event'])globalThis[name]=dom.window[name];
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
let requests=[];
globalThis.fetch=(url,init)=>new Promise((resolve,reject)=>requests.push({url,init,resolve,reject}));
const flush=async(fn=()=>{})=>act(async()=>{await fn();await new Promise(resolve=>setTimeout(resolve,0))});
const root=createRoot(document.getElementById('root'));
await flush(()=>root.render(React.createElement(SettingsOverview,{s:{mode:'demo',user:{id:'me',role:'member'}}})));
assert.match(document.body.textContent,/正在讀取設定摘要/);
assert.equal(requests[0].url,'/api/settings/overview');
await flush(()=>requests[0].resolve(new Response('{}',{status:404})));
assert.match(document.querySelector('[role=alert]').textContent,/設定摘要無法讀取/);
await flush(()=>document.querySelector('button').click());
