import assert from 'node:assert/strict';
import {build} from 'esbuild';
import fs from 'node:fs/promises';
const bundle=await build({entryPoints:[new URL('./src/dispatchPublishModel.ts',import.meta.url).pathname],bundle:true,write:false,platform:'node',format:'esm'});
const {parseWork,parsePreview,parseCommand,normalizeProposal,personHours,validateProposal,commandLabels,dispatchRequest}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const proposal={project_ref:'case-project',title:'測量',kind:'execution',primary_owner:'a',crew:['a','b','a'],start:'2026-10-19T08:00:00+08:00',end:'2026-10-19T12:00:00+08:00',instruments:[],vehicles:[]};
assert.deepEqual(normalizeProposal(proposal).crew,['a','b']);
assert.equal(personHours(normalizeProposal(proposal)),8);
assert.deepEqual(validateProposal(normalizeProposal(proposal)),[]);
assert.ok(validateProposal({...normalizeProposal(proposal),end:proposal.start}).includes('結束時間必須晚於開始時間。'));
assert.equal(parseCommand({command_id:'c',state:'pending'}).state,'pending');
assert.equal(commandLabels.pending,'處理中');
assert.equal(parseCommand({command_id:'c',state:'future'}).state,'unknown');
assert.equal(normalizeProposal({...proposal,phase:'future'}).phase,'unknown');
assert.deepEqual(parseWork({rows:[],source:{quality:{states:['future']}}}).states,['unknown']);
const row={task_id:'t',title:'待派',status:'待處理',planning_status:'unassigned',needs_me:['confirm_assignment'],allowed_actions:['assign','future'],source:'v4_task'};
const work=parseWork({rows:[row],progress:{status:{'待處理':99}},needs_me:[]});
assert.deepEqual(work.progress.status,{'待處理':1});
assert.equal(work.needs_me.length,1);
assert.deepEqual(work.rows[0].allowed_actions,['assign']);
assert.equal(parseWork({rows:[{...row,status:'future',planning_status:'future',kind:'future'}]}).rows[0].status,'unknown');
assert.equal(parseWork({rows:[{...row,scope_version:3}]}).rows[0].scope_version,'3');
assert.throws(()=>parseWork({}),/格式/);
const preview=parsePreview({preview_id:'p',preview_hash:'h',can_commit:true,required_seats:[{seat:'future',status:'future'}],feasibility:[{ref:'a',state:'future'}]});
assert.equal(preview.required_seats[0].seat,'unknown');
assert.equal(preview.feasibility[0].state,'unknown');
assert.equal(preview.can_commit,false);
assert.equal(parsePreview({preview_id:'p',preview_hash:'h',can_commit:true,feasibility:[{kind:'person',ref:'a',state:'feasible'}],required_seats:[{seat:'pm_final',status:'accepted'}]}).can_commit,false);
const fixtures=JSON.parse(await fs.readFile(new URL('./fixtures/dispatchPublishSynthetic.json',import.meta.url),'utf8'));
assert.equal(parseWork(fixtures.work).rows.length,4);
assert.deepEqual(parseWork(fixtures.work).progress.status,{'進行中':3,'待處理':1});
assert.deepEqual(parseWork(fixtures.stale).states,['stale']);
assert.equal(parsePreview({preview_id:'p',preview_hash:'h',can_commit:true,feasibility:[{kind:'person',ref:'a',state:'unknown'}]}).can_commit,false);
assert.equal(parsePreview({preview_id:'p',preview_hash:'h',can_commit:true,proposal:{manual_verifications:{a:'已核實'}},feasibility:[{kind:'person',ref:'a',state:'unknown'}]}).can_commit,true);
globalThis.fetch=async()=>new Response(JSON.stringify({command:{command_id:'async-command',state:'committed'}}),{status:202});
assert.equal(parseCommand(await dispatchRequest('/api/v2/dispatch/commits',new AbortController().signal,{command_id:'async-command',preview_id:'p'})).state,'pending');
console.log('dispatch publish model literal expectations passed');
