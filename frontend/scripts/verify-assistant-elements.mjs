import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright-core';
const base=process.env.ASSISTANT_DEMO_URL||'http://127.0.0.1:8137';
const output=process.env.ASSISTANT_SCREENSHOTS||'/tmp/ai-feat-chat-ui-screenshots';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const screenshot=async name=>{const path=`${output}/${name}.png`;await page.screenshot({path,fullPage:page.viewportSize().width>767});console.log(path)};
const ask=async text=>{
 await page.getByRole('button',{name:'新對話',exact:true}).click();
 await page.getByRole('textbox',{name:'詢問 AI 助理'}).fill(text);
 await page.getByRole('button',{name:'送出',exact:true}).click();
 await page.getByRole('button',{name:'停止回應',exact:true}).waitFor({state:'hidden'});
};
const theme=async name=>page.evaluate(name=>{localStorage.setItem('yx:theme',name);document.documentElement.dataset.theme=name},name);
try{
 await page.goto(`${base}/#view=assistant`);
 await page.getByRole('heading',{name:'AI 助理',exact:true}).waitFor();
 await theme('light');
 await ask('搜尋河岸案件');
 await page.locator('[data-slot=data-table]').scrollIntoViewIfNeeded();
 assert.equal(await page.locator('.assistant-data-wide').isVisible(),true);
 assert.equal(await page.locator('.assistant-data-cards').isVisible(),false);
 await page.getByRole('button',{name:'依案號排序'}).click();
 assert.equal(await page.locator('th[aria-sort]').getAttribute('aria-sort'),'ascending');
 await screenshot('table-desktop');
 await page.setViewportSize({width:390,height:1000});
 await page.locator('[data-slot=data-table]').scrollIntoViewIfNeeded();
 assert.equal(await page.locator('.assistant-data-wide').isVisible(),false);
 assert.equal(await page.locator('.assistant-data-cards').isVisible(),true);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.locator('[data-slot=data-table]').evaluate(el=>el.scrollIntoView({block:'start'}));
 await screenshot('table-390');
 await page.setViewportSize({width:1440,height:1100});
 await ask('河岸案件進度');
 await page.locator('[data-slot=chart]').scrollIntoViewIfNeeded();
 await page.locator('.assistant-chart-bar').first().hover();
 assert.match(await page.getByRole('tooltip').innerText(),/100%/);
 await page.getByRole('button',{name:'查看規劃的圖表提示'}).focus();
 assert.match(await page.getByRole('tooltip').innerText(),/100%/);
 await screenshot('chart-light');
 await theme('dark');
 await screenshot('chart-dark');
 await page.getByRole('button',{name:'這則回答沒有幫助',exact:true}).click();
 await page.getByRole('button',{name:'答錯',exact:true}).waitFor();
 await page.getByRole('button',{name:'這則回答沒有幫助',exact:true}).isEnabled();
 await page.waitForFunction(()=>!document.querySelector('[aria-label="這則回答沒有幫助"]').disabled);
 assert.equal(await page.getByRole('button',{name:'這則回答沒有幫助',exact:true}).getAttribute('aria-pressed'),'true');
 await screenshot('feedback-reasons');
 await page.getByRole('button',{name:'答錯',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('[aria-label="這則回答沒有幫助"]').disabled);
 assert.equal(await page.getByRole('button',{name:'答錯',exact:true}).getAttribute('aria-pressed'),'true');
 await screenshot('feedback-pressed');
 await page.getByRole('button',{name:'其他',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'評分未儲存'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'答錯',exact:true}).getAttribute('aria-pressed'),'true');
 await screenshot('feedback-error');
 await ask('模擬錯誤');
 await page.getByRole('alert').filter({hasText:'AI 服務暫時無法回應'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'這則回答有幫助',exact:true}).count(),0);
 await screenshot('reply-error');
 await ask('今天出勤');
 assert.equal(await page.locator('[data-slot=chart]').count(),1);
 assert.equal(await page.locator('[data-slot=data-table]').count(),1);
 await ask('案件負責人');
 assert.match(await page.locator('[data-slot=data-table]').innerText(),/節點指派資料未啟用/);
 await ask('部分案件');
 assert.match(await page.locator('[data-slot=data-table]').innerText(),/僅列出部分/);
 assert.deepEqual(errors,[]);
 console.log('Built demo artifact passed desktop and 390px container layout, no horizontal page overflow, sorting, chart focus tooltip, light/dark, feedback, rollback, reply error, and all five stream fixtures.');
}finally{await browser.close()}
