import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';
import {build} from 'esbuild';
import {chromium} from 'playwright-core';
const base=process.env.ASSISTANT_DEMO_URL||'http://127.0.0.1:8137';
const output=process.env.ASSISTANT_SCREENSHOTS||'/tmp/ai-pc-chat-screenshots';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const shot=async name=>{await page.screenshot({path:`${output}/${name}.png`,fullPage:true});console.log(`${output}/${name}.png`)};
const theme=async name=>page.evaluate(name=>{document.documentElement.dataset.theme=name},name);
const ask=async text=>{
 await page.getByRole('button',{name:'新對話',exact:true}).click();
 await page.getByRole('textbox',{name:'詢問 AI 助理'}).fill(text);
 await page.getByRole('button',{name:'送出',exact:true}).click();
};
const done=()=>page.getByRole('button',{name:'停止回應',exact:true}).waitFor({state:'hidden'});
try{
 await page.goto(`${base}/#view=assistant`);
 await page.locator('.assistant-suggestions').waitFor();
 await theme('light');await shot('empty-light');
 await page.getByRole('combobox',{name:'選擇 AI 助理'}).click();
 await shot('model-selector-light');
 await page.getByRole('option',{name:'GPT',exact:true}).click();
 await ask('表格');
 await page.locator('[data-slot=thinking-indicator]').waitFor();
 await shot('thinking-light');
 assert.equal(await page.locator('.assistant-tool').count(),0);
 await page.waitForFunction(()=>document.querySelector('[data-role=assistant]')?.textContent.includes('目前'));
 assert.equal(await page.locator('[data-slot=thinking-indicator]').count(),0,'thinking ends at first text');
 await shot('mid-stream-light');await done();await shot('table-light');
 assert.equal(await page.locator('[data-slot=data-table]').count(),1);
 await theme('dark');await shot('table-dark');
 await page.setViewportSize({width:390,height:844});await shot('table-mobile-dark');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await theme('light');await shot('table-mobile-light');
 await page.setViewportSize({width:1440,height:1000});await ask('圖表');await done();await shot('chart-light');
 await theme('dark');await shot('chart-dark');
 await page.getByRole('combobox',{name:'選擇 AI 助理'}).click();await shot('model-selector-dark');await page.keyboard.press('Escape');
 await ask('錯誤');await page.getByRole('alert').filter({hasText:'AI 服務暫時無法回應'}).waitFor();await shot('error-dark');
 await theme('light');await shot('error-light');
 await ask('長文');await done();
 const viewport=page.locator('.assistant-viewport');
 await viewport.evaluate(el=>{el.scrollTop=0;el.dispatchEvent(new Event('scroll'))});
 await page.getByRole('button',{name:'回到最新回答'}).waitFor({state:'visible'});
 assert.equal(await page.getByRole('button',{name:'回到最新回答'}).isEnabled(),true);
 await shot('scroll-up-light');await page.getByRole('button',{name:'回到最新回答'}).click();
 assert.doesNotMatch(await page.locator('.assistant-chat').innerText(),/不應顯示的工具標籤|回答依你可查看|重要資訊請再核對/);
 await page.goto(`${base}/#view=quotes`);await page.locator('.quote-table').waitFor();await shot('quotes-reference');
 const harness=await build({stdin:{contents:"import React from 'react';import {createRoot} from 'react-dom/client';import {AssistantChat} from './src/assistant/AssistantChat';createRoot(document.getElementById('root')).render(<AssistantChat projectId='project-a' compact/>);",resolveDir:new URL('..',import.meta.url).pathname,loader:'tsx'},bundle:true,write:false,minify:true,format:'iife',jsx:'automatic',loader:{'.css':'empty'}});
 const manifest=JSON.parse(await readFile(new URL('../dist/.vite/manifest.json',import.meta.url),'utf8'));
 const css=[...manifest['index.html'].css,...manifest['src/Assistant.tsx'].css].map(file=>`<link rel="stylesheet" href="/${file}">`).join('');
 await page.route('**/compact-harness',route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html lang="zh-Hant"><head>${css}</head><body><div id="root" style="width:420px;height:780px;margin:16px auto;padding:16px;background:var(--surface);border-radius:var(--radius-card)"></div><script>${harness.outputFiles[0].text.replaceAll('</script','<\/script')}</script></body></html>`}));
 await page.setViewportSize({width:480,height:844});await page.goto(`${base}/compact-harness`);
 await page.locator('.assistant-suggestions').waitFor();
 assert.equal(await page.locator('h1').count(),0);
 assert.ok(await page.locator('.assistant-thread').evaluate(el=>el.clientWidth)>350,'compact thread fills panel width');
 assert.equal(await page.locator('.assistant-suggestions button').count(),5);
 await theme('light');await shot('compact-420-light');
 await theme('dark');await shot('compact-420-dark');
 await ask('圖表');await done();await shot('compact-420-chart-dark');
 assert.equal(await page.locator('.assistant-chat').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
 assert.deepEqual(errors,[]);
 console.log('Built artifact passed model selection, table, chart, error, thinking, first delta, scroll control, and mobile overflow checks.');
}finally{await browser.close()}
